-- Classes 0 (Iniciação) a 9. max_score e pass_mark ficam NULL na Iniciação (sem notas).
CREATE TABLE grade_levels (
    id SMALLINT PRIMARY KEY,
    grade_number SMALLINT NOT NULL UNIQUE CHECK (grade_number BETWEEN 0 AND 9),
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(60) NOT NULL,
    stage VARCHAR(20) NOT NULL CHECK (stage IN ('preschool','primary','lower_secondary')),
    min_age SMALLINT NOT NULL,
    max_age SMALLINT NOT NULL,
    max_score SMALLINT,
    pass_mark SMALLINT,
    has_national_exam BOOLEAN NOT NULL DEFAULT false,
    assessment_regime VARCHAR(10) NOT NULL CHECK (assessment_regime IN ('none','lenient','strict')),
    CHECK (min_age <= max_age),
    CHECK (
        (stage = 'preschool' AND max_score IS NULL AND pass_mark IS NULL AND assessment_regime = 'none' AND NOT has_national_exam)
        OR (stage <> 'preschool' AND max_score > 0 AND pass_mark BETWEEN 1 AND max_score AND assessment_regime <> 'none')
    ),
    CHECK (has_national_exam = (assessment_regime = 'strict'))
);

