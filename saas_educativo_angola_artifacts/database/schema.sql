BEGIN;

CREATE TABLE institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    slug VARCHAR(120) NOT NULL UNIQUE,
    institution_type VARCHAR(30) NOT NULL CHECK (institution_type IN ('school','training_center','both')),
    approval_status VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (approval_status IN ('pending','under_review','approved','rejected','suspended')),
    operational_status VARCHAR(20) NOT NULL DEFAULT 'inactive'
        CHECK (operational_status IN ('inactive','active','suspended','closed')),
    email VARCHAR(254),
    phone VARCHAR(40),
    tax_identifier VARCHAR(80),
    address TEXT,
    municipality VARCHAR(120),
    province VARCHAR(120),
    approved_at TIMESTAMPTZ,
    approved_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, institution_type)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    email_verified_at TIMESTAMPTZ,
    password VARCHAR(255) NOT NULL,
    phone VARCHAR(40),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','blocked','pending')),
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE institutions
    ADD CONSTRAINT fk_institutions_approved_by
    FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL;

CREATE TABLE institution_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT REFERENCES institutions(id) ON DELETE SET NULL,
    institution_type VARCHAR(30) NOT NULL CHECK (institution_type IN ('school','training_center','both')),
    proposed_name VARCHAR(180) NOT NULL,
    applicant_name VARCHAR(180) NOT NULL,
    applicant_email VARCHAR(254) NOT NULL,
    applicant_phone VARCHAR(40),
    tax_identifier VARCHAR(80),
    province VARCHAR(120),
    municipality VARCHAR(120),
    submitted_documents JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','under_review','approved','rejected','info_requested')),
    review_notes TEXT,
    reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_applications_status_submitted ON institution_applications(status, submitted_at);

CREATE TABLE plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(60) NOT NULL UNIQUE,
    description TEXT,
    price NUMERIC(19,2) NOT NULL CHECK (price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA',
    billing_interval VARCHAR(20) NOT NULL CHECK (billing_interval IN ('monthly','quarterly','yearly')),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE plan_features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
    feature_key VARCHAR(100) NOT NULL,
    enabled BOOLEAN,
    numeric_limit BIGINT CHECK (numeric_limit IS NULL OR numeric_limit >= 0),
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (plan_id, feature_key)
);

CREATE TABLE subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    plan_id BIGINT NOT NULL REFERENCES plans(id) ON DELETE RESTRICT,
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','trialing','active','past_due','suspended','cancelled','expired')),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    next_billing_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, institution_id),
    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at)
);
CREATE INDEX idx_subscriptions_institution_status ON subscriptions(institution_id, status);

CREATE TABLE subscription_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    subscription_id BIGINT NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA',
    method VARCHAR(30) NOT NULL CHECK (method IN ('cash','bank_transfer','other_manual')),
    reference VARCHAR(120),
    status VARCHAR(24) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected','reversed')),
    paid_at TIMESTAMPTZ,
    recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (subscription_id, institution_id)
        REFERENCES subscriptions(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_subscription_payments_tenant_date ON subscription_payments(institution_id, paid_at);

CREATE TABLE institution_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(60) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','invited','revoked')),
    invited_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    joined_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, user_id),
    UNIQUE (id, institution_id)
);
CREATE INDEX idx_institution_user_user_status ON institution_user(user_id, status);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_code VARCHAR(80) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    preferred_name VARCHAR(100),
    birth_date DATE,
    gender VARCHAR(30),
    email VARCHAR(254),
    phone VARCHAR(40),
    address TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, student_code),
    UNIQUE (id, institution_id)
);
CREATE INDEX idx_students_tenant_name ON students(institution_id, last_name, first_name);
CREATE INDEX idx_students_tenant_status ON students(institution_id, status);

CREATE TABLE guardians (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(40),
    relationship_label VARCHAR(60),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, institution_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_guardians_tenant_name ON guardians(institution_id, last_name, first_name);

CREATE TABLE student_guardian (
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    guardian_id BIGINT NOT NULL,
    relationship_label VARCHAR(60),
    is_primary BOOLEAN NOT NULL DEFAULT false,
    can_view_finance BOOLEAN NOT NULL DEFAULT false,
    can_view_academic BOOLEAN NOT NULL DEFAULT true,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (institution_id, student_id, guardian_id),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (guardian_id, institution_id) REFERENCES guardians(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_student_guardian_guardian ON student_guardian(institution_id, guardian_id);

CREATE TABLE school_years (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    name VARCHAR(80) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','active','closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, name),
    UNIQUE (id, institution_id),
    CHECK (ends_on >= starts_on)
);
CREATE INDEX idx_school_years_tenant_status ON school_years(institution_id, status);

CREATE TABLE school_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    name VARCHAR(80) NOT NULL,
    level_order SMALLINT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, name),
    UNIQUE (id, institution_id)
);

CREATE TABLE classrooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    school_year_id BIGINT NOT NULL,
    school_class_id BIGINT NOT NULL,
    name VARCHAR(80) NOT NULL,
    shift VARCHAR(30),
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    room_label VARCHAR(80),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, school_year_id, name),
    UNIQUE (id, institution_id),
    FOREIGN KEY (school_year_id, institution_id) REFERENCES school_years(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (school_class_id, institution_id) REFERENCES school_classes(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_classrooms_tenant_year ON classrooms(institution_id, school_year_id, status);

CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    school_year_id BIGINT NOT NULL,
    school_class_id BIGINT NOT NULL,
    classroom_id BIGINT,
    enrollment_code VARCHAR(80) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','approved','active','cancelled','completed','transferred')),
    enrolled_at DATE,
    approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, enrollment_code),
    UNIQUE (institution_id, student_id, school_year_id),
    UNIQUE (id, institution_id),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (school_year_id, institution_id) REFERENCES school_years(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (school_class_id, institution_id) REFERENCES school_classes(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (classroom_id, institution_id) REFERENCES classrooms(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_enrollments_tenant_year_class_status ON enrollments(institution_id, school_year_id, classroom_id, status);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(180) NOT NULL,
    description TEXT,
    duration_hours INTEGER CHECK (duration_hours IS NULL OR duration_hours > 0),
    default_price NUMERIC(19,2) CHECK (default_price IS NULL OR default_price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA',
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, code),
    UNIQUE (id, institution_id)
);

CREATE TABLE course_editions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    course_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    starts_on DATE,
    ends_on DATE,
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    price NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA',
    status VARCHAR(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','open','in_progress','completed','cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, code),
    UNIQUE (id, institution_id),
    FOREIGN KEY (course_id, institution_id) REFERENCES courses(id, institution_id) ON DELETE RESTRICT,
    CHECK (ends_on IS NULL OR starts_on IS NULL OR ends_on >= starts_on)
);
CREATE INDEX idx_course_editions_tenant_status_dates ON course_editions(institution_id, status, starts_on);

CREATE TABLE training_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    course_edition_id BIGINT NOT NULL,
    enrollment_code VARCHAR(80) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','approved','active','completed','cancelled','withdrawn')),
    enrolled_at DATE,
    final_result VARCHAR(30),
    completed_at DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, enrollment_code),
    UNIQUE (institution_id, student_id, course_edition_id),
    UNIQUE (id, institution_id),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (course_edition_id, institution_id) REFERENCES course_editions(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_training_enrollments_tenant_edition_status ON training_enrollments(institution_id, course_edition_id, status);

CREATE TABLE attendance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    enrollment_id BIGINT,
    training_enrollment_id BIGINT,
    session_date DATE NOT NULL,
    session_label VARCHAR(120),
    status VARCHAR(20) NOT NULL CHECK (status IN ('present','absent','late','excused')),
    recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (enrollment_id IS NOT NULL AND training_enrollment_id IS NULL)
        OR (enrollment_id IS NULL AND training_enrollment_id IS NOT NULL)
    ),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (enrollment_id, institution_id) REFERENCES enrollments(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (training_enrollment_id, institution_id) REFERENCES training_enrollments(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_attendance_tenant_date_status ON attendance_records(institution_id, session_date, status);

CREATE TABLE charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    enrollment_id BIGINT,
    training_enrollment_id BIGINT,
    code VARCHAR(80) NOT NULL,
    description VARCHAR(240) NOT NULL,
    category VARCHAR(60) NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA',
    due_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('draft','open','partially_paid','paid','void','written_off')),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, code),
    UNIQUE (id, institution_id),
    CHECK (
        (enrollment_id IS NOT NULL AND training_enrollment_id IS NULL)
        OR (enrollment_id IS NULL AND training_enrollment_id IS NOT NULL)
    ),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (enrollment_id, institution_id) REFERENCES enrollments(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (training_enrollment_id, institution_id) REFERENCES training_enrollments(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_charges_tenant_status_due ON charges(institution_id, status, due_date);
CREATE INDEX idx_charges_tenant_student ON charges(institution_id, student_id, issued_at);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    payment_code VARCHAR(80) NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA',
    method VARCHAR(30) NOT NULL CHECK (method IN ('cash','bank_transfer','other_manual')),
    status VARCHAR(20) NOT NULL DEFAULT 'confirmed' CHECK (status IN ('pending','confirmed','reversed')),
    reference VARCHAR(120),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reversed_at TIMESTAMPTZ,
    reversal_reason TEXT,
    idempotency_key VARCHAR(120),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, payment_code),
    UNIQUE (institution_id, idempotency_key),
    UNIQUE (id, institution_id),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_payments_tenant_paid_at ON payments(institution_id, paid_at);
CREATE INDEX idx_payments_tenant_student ON payments(institution_id, student_id, paid_at);

CREATE TABLE payment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    payment_id BIGINT NOT NULL,
    charge_id BIGINT NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, payment_id, charge_id),
    FOREIGN KEY (payment_id, institution_id) REFERENCES payments(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (charge_id, institution_id) REFERENCES charges(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_payment_allocations_charge ON payment_allocations(institution_id, charge_id);

CREATE TABLE receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    payment_id BIGINT NOT NULL,
    receipt_code VARCHAR(100) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    issued_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'issued' CHECK (status IN ('issued','void')),
    void_reason TEXT,
    document_path TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, receipt_code),
    UNIQUE (institution_id, payment_id),
    FOREIGN KEY (payment_id, institution_id) REFERENCES payments(id, institution_id) ON DELETE RESTRICT
);

CREATE TABLE cash_registers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    opened_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    closed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    opening_amount NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (opening_amount >= 0),
    expected_closing_amount NUMERIC(19,2),
    actual_closing_amount NUMERIC(19,2),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed','reconciled')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, institution_id)
);
CREATE INDEX idx_cash_registers_tenant_status ON cash_registers(institution_id, status, opened_at);

CREATE TABLE certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    training_enrollment_id BIGINT NOT NULL,
    certificate_code VARCHAR(100) NOT NULL,
    verification_code VARCHAR(100) NOT NULL UNIQUE,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    issued_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'issued' CHECK (status IN ('issued','revoked')),
    revoked_at TIMESTAMPTZ,
    revocation_reason TEXT,
    document_path TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, certificate_code),
    UNIQUE (institution_id, training_enrollment_id),
    FOREIGN KEY (training_enrollment_id, institution_id) REFERENCES training_enrollments(id, institution_id) ON DELETE RESTRICT
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    owner_type VARCHAR(80) NOT NULL,
    owner_id BIGINT NOT NULL,
    document_type VARCHAR(80) NOT NULL,
    storage_disk VARCHAR(80) NOT NULL DEFAULT 'private',
    storage_path TEXT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    mime_type VARCHAR(120),
    size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes >= 0),
    checksum_sha256 CHAR(64),
    uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, storage_path)
);
CREATE INDEX idx_documents_owner ON documents(institution_id, owner_type, owner_id);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT REFERENCES institutions(id) ON DELETE RESTRICT,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(120) NOT NULL,
    resource_type VARCHAR(120) NOT NULL,
    resource_id VARCHAR(120),
    request_id VARCHAR(120),
    ip_address INET,
    user_agent TEXT,
    before_data JSONB,
    after_data JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_tenant_created ON audit_logs(institution_id, created_at DESC);
CREATE INDEX idx_audit_actor_created ON audit_logs(actor_user_id, created_at DESC);

COMMIT;
