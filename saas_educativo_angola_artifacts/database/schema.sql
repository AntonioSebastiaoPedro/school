CREATE TABLE school_years (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    name VARCHAR(9) NOT NULL CHECK (name ~ '^[0-9]{4}/[0-9]{4}$'),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','active','closed')),
    settings JSONB NOT NULL DEFAULT '{"trimesters":[1,2,3]}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, name),
    UNIQUE (id, institution_id),
    CHECK (ends_on >= starts_on),
    EXCLUDE USING gist (institution_id WITH =, daterange(starts_on, ends_on, '[]') WITH &&)
);
CREATE INDEX idx_school_years_tenant_status ON school_years(institution_id, status);
-- Um único ano activo por instituição
CREATE UNIQUE INDEX uq_school_years_active ON school_years(institution_id) WHERE status = 'active';

