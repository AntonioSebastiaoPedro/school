CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    school_year_id BIGINT NOT NULL,
    grade_level_id SMALLINT NOT NULL REFERENCES grade_levels(id) ON DELETE RESTRICT,
    section_id BIGINT,
    enrollment_code VARCHAR(80) NOT NULL,
    roll_number INTEGER CHECK (roll_number IS NULL OR roll_number > 0),
    enrollment_type VARCHAR(20) NOT NULL DEFAULT 'new' CHECK (enrollment_type IN ('new','renewal','transfer_in')),
    previous_enrollment_id BIGINT,
    origin_school VARCHAR(255),
    is_repeater BOOLEAN NOT NULL DEFAULT false,
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','approved','active','cancelled','completed','dropped','transferred')),
    enrolled_at DATE,
    approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, enrollment_code),
    UNIQUE (institution_id, student_id, school_year_id),
    UNIQUE (id, institution_id),
    UNIQUE (id, grade_level_id, institution_id),
    CHECK (section_id IS NOT NULL OR status IN ('pending','approved','cancelled')),
    CHECK (previous_enrollment_id IS NULL OR previous_enrollment_id <> id),
    FOREIGN KEY (student_id, institution_id) REFERENCES students(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (school_year_id, institution_id) REFERENCES school_years(id, institution_id) ON DELETE RESTRICT,
    -- a turma tem de pertencer ao mesmo ano e à mesma classe da matrícula
    FOREIGN KEY (section_id, school_year_id, grade_level_id, institution_id)
        REFERENCES sections(id, school_year_id, grade_level_id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (previous_enrollment_id, institution_id) REFERENCES enrollments(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_enrollments_tenant_year_section_status ON enrollments(institution_id, school_year_id, section_id, status);
CREATE UNIQUE INDEX uq_enrollments_roll ON enrollments(institution_id, section_id, roll_number) WHERE roll_number IS NOT NULL;

