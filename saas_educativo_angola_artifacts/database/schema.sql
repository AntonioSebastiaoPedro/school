-- term 1-3: MAC, NPP, NPT; term 0: exame (NE) e recurso (NER).
-- O valor máximo por classe e a ausência de notas na Iniciação são validados no serviço.
CREATE TABLE grades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    enrollment_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    term SMALLINT NOT NULL CHECK (term BETWEEN 0 AND 3),
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('mac','npp','npt','exam','resit')),
    value NUMERIC(5,2) NOT NULL CHECK (value >= 0),
    recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (institution_id, enrollment_id, subject_id, term, kind),
    CHECK (
        (kind IN ('exam','resit') AND term = 0)
        OR (kind IN ('mac','npp','npt') AND term BETWEEN 1 AND 3)
    ),
    FOREIGN KEY (enrollment_id, institution_id) REFERENCES enrollments(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (subject_id, institution_id) REFERENCES subjects(id, institution_id) ON DELETE RESTRICT
);
CREATE INDEX idx_grades_enrollment ON grades(institution_id, enrollment_id, subject_id);

-- Médias materializadas; só guardam valores positivos (0 = sem nota = NULL)
CREATE TABLE grade_averages (
    institution_id BIGINT NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    enrollment_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    term1_avg NUMERIC(4,1),
    term2_avg NUMERIC(4,1),
    term3_avg NUMERIC(4,1),
    year_avg NUMERIC(4,1),
    exam NUMERIC(5,2),
    resit NUMERIC(5,2),
    final_avg SMALLINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (institution_id, enrollment_id, subject_id),
    FOREIGN KEY (enrollment_id, institution_id) REFERENCES enrollments(id, institution_id) ON DELETE RESTRICT,
    FOREIGN KEY (subject_id, institution_id) REFERENCES subjects(id, institution_id) ON DELETE RESTRICT
);

